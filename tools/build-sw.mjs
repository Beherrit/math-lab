// Rewrites sw.js: the precache list comes from the real files under css/, js/ and icons/.
// Run after adding, moving or deleting files:  node tools/build-sw.mjs
// To force every browser to refetch, raise CACHE_NAME below (mathlab-v2 -> mathlab-v3).
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const CACHE_NAME = 'mathlab-v11';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
function walk(dir) {
  return readdirSync(join(root, dir)).sort().flatMap(name => {
    const rel = `${dir}/${name}`;
    return statSync(join(root, rel)).isDirectory() ? walk(rel) : [`./${rel}`];
  });
}
const files = ['./', './manifest.webmanifest', ...walk('css'), ...walk('js'), ...walk('icons')];
const list = files.map(f => `  '${f}',`).join('\n');
const sw = `// Generated by tools/build-sw.mjs. Do not edit the list by hand.
const CACHE = '${CACHE_NAME}';
const PRECACHE = [
${list}
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE).then(cache => cache.addAll(PRECACHE)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Network first, fall back to the cache when offline.
self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET') return;
  event.respondWith(
    fetch(req)
      .then(res => {
        if (res && (res.ok || res.type === 'opaque')) {
          const copy = res.clone();
          caches.open(CACHE).then(cache => cache.put(req, copy));
        }
        return res;
      })
      .catch(() => caches.match(req).then(hit => hit || (req.mode === 'navigate' ? caches.match('./') : undefined)))
  );
});
`;
writeFileSync(join(root, 'sw.js'), sw);
console.log(`sw.js: ${files.length} files, cache ${CACHE_NAME}`);
